    [SchemaTestPostgresFact]
    public async Task PostgreSqlSchemaTestDatabase_MemoryIngestionJob_IdentityGeneratedOnInsert()
    {
        var credentials = DiscoverPostgresCredentials();
        Assert.NotNull(credentials);

        var connString = $"Host={credentials.Value.Host};Port={credentials.Value.Port};Database={credentials.Value.Database};Username={credentials.Value.Username};Password={credentials.Value.Password};";

        var options = new DbContextOptionsBuilder<KairoDbContext>()
            .UseNpgsql(connString, o => o.UseVector())
            .Options;

        using var context = new KairoDbContext(options);

        var canConnect = await context.Database.CanConnectAsync();
        Assert.True(canConnect, "Expected successful connection to kairo_schema_test database.");

        // Find or create parent user and project
        var user = await context.Users.FirstOrDefaultAsync();
        if (user == null)
        {
            user = new Users
            {
                Email = "schema_test@kairo.ai",
                AccountStatus = 1,
                CreatedAt = DateTime.UtcNow,
                UpdatedAt = DateTime.UtcNow
            };
            context.Users.Add(user);
            await context.SaveChangesAsync();
        }

        var project = await context.Projects.FirstOrDefaultAsync(p => p.UserId == user.UserId);
        if (project == null)
        {
            project = new Projects
            {
                UserId = user.UserId,
                Name = "Schema Test Project",
                CreatedAt = DateTime.UtcNow,
                UpdatedAt = DateTime.UtcNow
            };
            context.Projects.Add(project);
            await context.SaveChangesAsync();
        }

        // Insert job without specifying JobId (value generated on add)
        var newJob = new MemoryIngestionJob
        {
            ProjectId = project.ProjectId,
            UserId = user.UserId,
            JobType = "SchemaVerificationTest",
            Status = "Pending",
            AvailableAt = DateTime.UtcNow,
            CreatedAt = DateTime.UtcNow
        };

        try
        {
            context.MemoryIngestionJobs.Add(newJob);
            await context.SaveChangesAsync();

            Assert.True(newJob.JobId > 0, "Expected database identity to assign a positive BIGINT JobId.");

            // Read back
            var retrievedJob = await context.MemoryIngestionJobs.FindAsync(newJob.JobId);
            Assert.NotNull(retrievedJob);
            Assert.Equal("SchemaVerificationTest", retrievedJob.JobType);
        }
        finally
        {
            if (newJob.JobId > 0)
            {
                try
                {
                    var toClean = await context.MemoryIngestionJobs.FindAsync(newJob.JobId);
                    if (toClean != null)
                    {
                        context.MemoryIngestionJobs.Remove(toClean);
                        await context.SaveChangesAsync();
                    }
                }
                catch { /* best-effort cleanup */ }
            }
        }
    }

    [SchemaTestPostgresFact]
    public async Task PostgreSqlSchemaTestDatabase_PgvectorExtension_IsActive()
    {
        var credentials = DiscoverPostgresCredentials();
        Assert.NotNull(credentials);

        var connString = $"Host={credentials.Value.Host};Port={credentials.Value.Port};Database={credentials.Value.Database};Username={credentials.Value.Username};Password={credentials.Value.Password};";

        using var conn = new NpgsqlConnection(connString);
        await conn.OpenAsync();

        using var cmd = new NpgsqlCommand("SELECT extname, extversion FROM pg_extension WHERE extname = 'vector';", conn);
        using var reader = await cmd.ExecuteReaderAsync();

        Assert.True(await reader.ReadAsync(), "Expected pgvector extension to be installed in the schema test database.");
        Assert.Equal("vector", reader.GetString(0));
        Assert.False(string.IsNullOrWhiteSpace(reader.GetString(1)));
    }

    internal static bool CanConnectToSchemaTestDb()
    {
        var creds = DiscoverPostgresCredentials();
        if (creds == null) return false;
        try
        {
            var connStr = $"Host={creds.Value.Host};Port={creds.Value.Port};Database={creds.Value.Database};Username={creds.Value.Username};Password={creds.Value.Password};";
            using var conn = new NpgsqlConnection(connStr);
            conn.Open();
            return true;
        }
        catch
        {
            return false;
        }
    }

    private static (string Host, int Port, string Database, string Username, string Password)? DiscoverPostgresCredentials()
    {
        var host = Environment.GetEnvironmentVariable("POSTGRES_HOST") ?? "127.0.0.1";
        var portStr = Environment.GetEnvironmentVariable("POSTGRES_HOST_PORT") ?? "5433";
        int.TryParse(portStr, out var port);
        if (port == 0) port = 5433;
        var user = Environment.GetEnvironmentVariable("KAIRO_APP_USER") ?? "kairo_dev";
        var db = Environment.GetEnvironmentVariable("POSTGRES_SCHEMA_TEST_DB") ?? "kairo_schema_test";

        var envPass = Environment.GetEnvironmentVariable("KAIRO_APP_PASSWORD");
        if (!string.IsNullOrWhiteSpace(envPass))
        {
            return (host, port, db, user, envPass);
        }

        var baseDir = AppDomain.CurrentDomain.BaseDirectory;
        var dir = new DirectoryInfo(baseDir);
        while (dir != null && !File.Exists(Path.Combine(dir.FullName, "infrastructure", "docker", ".env")))
        {
            dir = dir.Parent;
        }

        if (dir != null)
        {
            var envFilePath = Path.Combine(dir.FullName, "infrastructure", "docker", ".env");
            var lines = File.ReadAllLines(envFilePath);
            string? discoveredUser = null;
            string? discoveredPass = null;
            string? discoveredPort = null;
            foreach (var rawLine in lines)
            {
                var line = rawLine.Trim();
                if (line.StartsWith('#') || !line.Contains('=')) continue;
                var parts = line.Split('=', 2);
                var key = parts[0].Trim();
                var val = parts[1].Trim();
                if (key == "KAIRO_APP_USER") discoveredUser = val;
                if (key == "KAIRO_APP_PASSWORD") discoveredPass = val;
                if (key == "POSTGRES_HOST_PORT") discoveredPort = val;
            }

            if (!string.IsNullOrWhiteSpace(discoveredPass))
            {
                if (!string.IsNullOrWhiteSpace(discoveredUser)) user = discoveredUser;
                if (int.TryParse(discoveredPort, out var p)) port = p;
                return (host, port, db, user, discoveredPass);
            }
        }

        return null;
    }
}

/// <summary>
/// Custom xUnit fact attribute that conditionally skips schema validation tests
/// when the isolated kairo_schema_test database is unreachable.
/// Prevents false-positive test passes from silent early returns.
/// </summary>
public sealed class SchemaTestPostgresFactAttribute : FactAttribute
{
    public SchemaTestPostgresFactAttribute()
    {
        if (!Phase4CPostgreSqlSchemaValidationUnitTests.CanConnectToSchemaTestDb())
        {
            Skip = "kairo_schema_test PostgreSQL database is not reachable. Ensure PostgreSQL is running on port 5433 with kairo_schema_test initialized.";
        }
    }
}
