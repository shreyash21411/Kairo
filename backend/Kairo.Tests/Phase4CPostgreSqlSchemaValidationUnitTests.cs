    [Fact]
    public void BaselineSqlFile_Exists_AndDefinesAll19EntitiesAndVectorExtension()
    {
        var baseDir = AppDomain.CurrentDomain.BaseDirectory;
        var dir = new DirectoryInfo(baseDir);
        while (dir != null && !File.Exists(Path.Combine(dir.FullName, "infrastructure", "kairo_schema_postgresql_baseline.sql")))
        {
            dir = dir.Parent;
        }

        Assert.NotNull(dir);
        var sqlPath = Path.Combine(dir.FullName, "infrastructure", "kairo_schema_postgresql_baseline.sql");
        Assert.True(File.Exists(sqlPath));

        var sqlContent = File.ReadAllText(sqlPath);

        // Extension check
        Assert.Contains("CREATE EXTENSION IF NOT EXISTS vector;", sqlContent);

        // All 19 expected tables
        string[] expectedTables =
        [
            "Users",
            "Projects",
            "UserMemorySettings",
            "MemorySettingHistory",
            "AuthenticationIdentities",
            "RefreshTokens",
            "ApiKeys",
            "Chats",
            "Messages",
            "MemoryScopes",
            "Memories",
            "MemoryEmbeddings",
            "MemoryVersions",
            "MemoryCategories",
            "Entities",
            "MemoryEntities",
            "EntityRelationships",
            "RelationshipEvidence",
            "MemoryIngestionJobs"
        ];

        foreach (var table in expectedTables)
        {
            Assert.Contains($"CREATE TABLE IF NOT EXISTS \"{table}\"", sqlContent);
        }

        // Identity generation requirement
        Assert.Contains("\"JobId\"             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sqlContent);
    }

