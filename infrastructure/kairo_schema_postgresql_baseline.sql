-- =============================================================================
-- Kairo PostgreSQL Baseline Schema
-- File: infrastructure/kairo_schema_postgresql_baseline.sql
--
-- Purpose:
--   Complete baseline schema for Kairo on PostgreSQL 17 with pgvector 0.8+.
--   Defines all 19 application entities with full constraints, primary keys,
--   foreign keys, default values, and supporting indexes in dependency order.
--
-- Re-execution & Idempotency Semantics:
--   • Idempotent: Uses CREATE EXTENSION IF NOT EXISTS, CREATE TABLE IF NOT EXISTS,
--     and CREATE INDEX IF NOT EXISTS.
--   • Safe to execute repeatedly against an empty or already-initialized database.
--   • Non-destructive: Does NOT drop, truncate, or alter existing data.
-- =============================================================================

-- ─────────────────────────────────────────────────────────────────────────────
-- 0. Extensions
-- ─────────────────────────────────────────────────────────────────────────────
CREATE EXTENSION IF NOT EXISTS vector;

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. Users (Root principal table)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "Users" (
    "UserId"            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Email"             VARCHAR(320) NOT NULL,
    "PasswordHash"      VARCHAR(500) NULL,
    "IsEmailVerified"   BOOLEAN NOT NULL DEFAULT FALSE,
    "AccountStatus"     SMALLINT NOT NULL DEFAULT 1,
    "CreatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "LastLoginAt"       TIMESTAMPTZ NULL,

    CONSTRAINT "UQ_Users_Email" UNIQUE ("Email")
);

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. Projects (Tenant / workspace boundary)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "Projects" (
    "ProjectId"         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId"            BIGINT NOT NULL,
    "Name"              VARCHAR(200) NOT NULL,
    "CreatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "IsDeleted"         BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT "FK_Projects_Users"
        FOREIGN KEY ("UserId") REFERENCES "Users"("UserId")
);

CREATE INDEX IF NOT EXISTS "IX_Projects_UserId"
    ON "Projects" ("UserId");

-- ─────────────────────────────────────────────────────────────────────────────
-- 3. UserMemorySettings (1-to-1 with Users)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "UserMemorySettings" (
    "UserId"            BIGINT PRIMARY KEY,
    "IsEnabled"         BOOLEAN NOT NULL DEFAULT TRUE,
    "EnabledAt"         TIMESTAMPTZ NULL,
    "DisabledAt"        TIMESTAMPTZ NULL,
    "UpdatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "FK_UserMemorySettings_Users"
        FOREIGN KEY ("UserId") REFERENCES "Users"("UserId")
);

-- ─────────────────────────────────────────────────────────────────────────────
-- 4. MemorySettingHistory (Audit log for memory setting changes)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "MemorySettingHistory" (
    "MemorySettingHistoryId" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId"                 BIGINT NOT NULL,
    "Action"                 VARCHAR(20) NOT NULL,
    "ChangedAt"              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "FK_MemorySettingHistory_Users"
        FOREIGN KEY ("UserId") REFERENCES "Users"("UserId")
);

CREATE INDEX IF NOT EXISTS "IX_MemorySettingHistory_UserId_ChangedAt"
    ON "MemorySettingHistory" ("UserId", "ChangedAt" DESC);

-- ─────────────────────────────────────────────────────────────────────────────
-- 5. AuthenticationIdentities (External OAuth and identity providers)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "AuthenticationIdentities" (
    "AuthenticationIdentityId" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId"                   BIGINT NOT NULL,
    "Provider"                 VARCHAR(50) NOT NULL,
    "ProviderSubject"          VARCHAR(320) NOT NULL,
    "PasswordHash"             VARCHAR(500) NULL,
    "CreatedAt"                TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt"                TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "UQ_AuthenticationIdentities_Provider_Subject"
        UNIQUE ("Provider", "ProviderSubject"),
    CONSTRAINT "FK_AuthenticationIdentities_Users"
        FOREIGN KEY ("UserId") REFERENCES "Users"("UserId")
);

-- ─────────────────────────────────────────────────────────────────────────────
-- 6. RefreshTokens (JWT refresh tokens with rotation family tracking)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "RefreshTokens" (
    "RefreshTokenId"    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId"            BIGINT NOT NULL,
    "TokenHash"         VARCHAR(128) NOT NULL,
    "FamilyId"          UUID NOT NULL,
    "ExpiresAt"         TIMESTAMPTZ NOT NULL,
    "CreatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "RevokedAt"         TIMESTAMPTZ NULL,
    "ReplacedByTokenId" BIGINT NULL,

    CONSTRAINT "UQ_RefreshTokens_TokenHash" UNIQUE ("TokenHash"),
    CONSTRAINT "FK_RefreshTokens_Users"
        FOREIGN KEY ("UserId") REFERENCES "Users"("UserId"),
    CONSTRAINT "FK_RefreshTokens_ReplacedBy"
        FOREIGN KEY ("ReplacedByTokenId") REFERENCES "RefreshTokens"("RefreshTokenId")
);

-- ─────────────────────────────────────────────────────────────────────────────
-- 7. ApiKeys (Project-scoped API access keys)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "ApiKeys" (
    "ApiKeyId"          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ProjectId"         BIGINT NOT NULL,
    "KeyHash"           VARCHAR(256) NOT NULL,
    "KeyPrefix"         VARCHAR(20) NOT NULL,
    "Name"              VARCHAR(100) NOT NULL,
    "IsActive"          BOOLEAN NOT NULL DEFAULT TRUE,
    "CreatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "LastUsedAt"        TIMESTAMPTZ NULL,
    "ExpiresAt"         TIMESTAMPTZ NULL,

    CONSTRAINT "UX_ApiKeys_KeyHash" UNIQUE ("KeyHash"),
    CONSTRAINT "FK_ApiKeys_Projects"
        FOREIGN KEY ("ProjectId") REFERENCES "Projects"("ProjectId")
);

CREATE INDEX IF NOT EXISTS "IX_ApiKeys_Active"
    ON "ApiKeys" ("KeyHash", "IsActive");
CREATE INDEX IF NOT EXISTS "IX_ApiKeys_ProjectId"
    ON "ApiKeys" ("ProjectId");

-- ─────────────────────────────────────────────────────────────────────────────
-- 8. Chats (Conversation sessions)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "Chats" (
    "ChatId"                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId"                 BIGINT NOT NULL,
    "ProjectId"              BIGINT NULL,
    "ExternalConversationId" VARCHAR(200) NOT NULL,
    "Source"                 VARCHAR(50) NOT NULL,
    "Name"                   VARCHAR(500) NULL,
    "CreatedAt"              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt"              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "IsDeleted"              BOOLEAN NOT NULL DEFAULT FALSE,
    "ProcessingStatus"       SMALLINT NOT NULL DEFAULT 1,
    "ProcessingStartedAt"    TIMESTAMPTZ NULL,
    "ProcessedAt"            TIMESTAMPTZ NULL,
    "ProcessingError"        VARCHAR(2000) NULL,
    "RawChatStatus"          SMALLINT NOT NULL DEFAULT 1,
    "RawChatRetentionUntil"  TIMESTAMPTZ NULL,
    "ArchivedAt"             TIMESTAMPTZ NULL,

    CONSTRAINT "FK_Chats_Users"
        FOREIGN KEY ("UserId") REFERENCES "Users"("UserId"),
    CONSTRAINT "FK_Chats_Projects"
        FOREIGN KEY ("ProjectId") REFERENCES "Projects"("ProjectId")
);

CREATE INDEX IF NOT EXISTS "IX_Chats_ExternalConversation"
    ON "Chats" ("Source", "ExternalConversationId");
CREATE INDEX IF NOT EXISTS "IX_Chats_ProjectId"
    ON "Chats" ("ProjectId");
CREATE INDEX IF NOT EXISTS "IX_Chats_UserId"
    ON "Chats" ("UserId");

-- ─────────────────────────────────────────────────────────────────────────────
-- 9. Messages (Individual chat messages)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "Messages" (
    "MessageId"         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ChatId"            BIGINT NOT NULL,
    "ExternalMessageId" VARCHAR(200) NOT NULL,
    "Role"              VARCHAR(30) NOT NULL,
    "Content"           TEXT NOT NULL,
    "CreatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "IsDeleted"         BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT "FK_Messages_Chats"
        FOREIGN KEY ("ChatId") REFERENCES "Chats"("ChatId")
);

CREATE INDEX IF NOT EXISTS "IX_Messages_ChatId"
    ON "Messages" ("ChatId");
CREATE INDEX IF NOT EXISTS "IX_Messages_ExternalMessageId"
    ON "Messages" ("ExternalMessageId");

-- ─────────────────────────────────────────────────────────────────────────────
-- 10. MemoryScopes (Multi-dimensional partition / scope boundary)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "MemoryScopes" (
    "ScopeId"           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ProjectId"         BIGINT NOT NULL,
    "ActorId"           VARCHAR(128) NOT NULL,
    "UserId"            VARCHAR(256) NULL,
    "AgentId"           VARCHAR(256) NULL,
    "SessionId"         VARCHAR(256) NULL,
    "RunId"             VARCHAR(256) NULL,
    "CreatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "UX_MemoryScopes_ProjectId_ActorId"
        UNIQUE ("ProjectId", "ActorId"),
    CONSTRAINT "FK_MemoryScopes_Projects"
        FOREIGN KEY ("ProjectId") REFERENCES "Projects"("ProjectId")
);

CREATE INDEX IF NOT EXISTS "IX_MemoryScopes_ProjectId"
    ON "MemoryScopes" ("ProjectId");
CREATE INDEX IF NOT EXISTS "IX_MemoryScopes_MultiDim"
    ON "MemoryScopes" ("ProjectId", "UserId", "AgentId", "SessionId", "RunId");

-- ─────────────────────────────────────────────────────────────────────────────
-- 11. Memories (Canonical long-term memories)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "Memories" (
    "MemoryId"          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId"            BIGINT NOT NULL,
    "Content"           TEXT NOT NULL,
    "MemoryType"        VARCHAR(50) NULL,
    "SourceChatId"      BIGINT NULL,
    "IsActive"          BOOLEAN NOT NULL DEFAULT TRUE,
    "CreatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "ScopeId"           BIGINT NULL,
    "OccurredAt"        TIMESTAMPTZ NULL,
    "Metadata"          TEXT NULL,
    "ExpiresAt"         TIMESTAMPTZ NULL,

    CONSTRAINT "FK_Memories_Users"
        FOREIGN KEY ("UserId") REFERENCES "Users"("UserId"),
    CONSTRAINT "FK_Memories_SourceChat"
        FOREIGN KEY ("SourceChatId") REFERENCES "Chats"("ChatId"),
    CONSTRAINT "FK_Memories_MemoryScopes"
        FOREIGN KEY ("ScopeId") REFERENCES "MemoryScopes"("ScopeId")
);

CREATE INDEX IF NOT EXISTS "IX_Memories_ScopeId"
    ON "Memories" ("ScopeId");
CREATE INDEX IF NOT EXISTS "IX_Memories_SourceChatId"
    ON "Memories" ("SourceChatId");
CREATE INDEX IF NOT EXISTS "IX_Memories_UserId_IsActive"
    ON "Memories" ("UserId", "IsActive");
CREATE INDEX IF NOT EXISTS "IX_Memories_OccurredAt"
    ON "Memories" ("OccurredAt");
CREATE INDEX IF NOT EXISTS "IX_Memories_CreatedAt"
    ON "Memories" ("CreatedAt");
CREATE INDEX IF NOT EXISTS "IX_Memories_UpdatedAt"
    ON "Memories" ("UpdatedAt");
CREATE INDEX IF NOT EXISTS "IX_Memories_ExpiresAt"
    ON "Memories" ("ExpiresAt");
CREATE INDEX IF NOT EXISTS "IX_Memories_Active_ExpiresAt"
    ON "Memories" ("UserId", "IsActive", "ExpiresAt");

-- ─────────────────────────────────────────────────────────────────────────────
-- 12. MemoryEmbeddings (Vector embeddings associated with memories)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "MemoryEmbeddings" (
    "EmbeddingId"       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "MemoryId"          BIGINT NOT NULL,
    "Model"             VARCHAR(150) NOT NULL,
    "Dimensions"        INT NOT NULL,
    "VectorData"        TEXT NOT NULL,
    "CreatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "FK_MemoryEmbeddings_Memories"
        FOREIGN KEY ("MemoryId") REFERENCES "Memories"("MemoryId")
);

CREATE INDEX IF NOT EXISTS "IX_MemoryEmbeddings_MemoryId"
    ON "MemoryEmbeddings" ("MemoryId");

-- ─────────────────────────────────────────────────────────────────────────────
-- 13. MemoryVersions (Audit trail and history of memory modifications)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "MemoryVersions" (
    "MemoryVersionId"   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "MemoryId"          BIGINT NOT NULL,
    "Content"           TEXT NOT NULL,
    "Operation"         VARCHAR(30) NOT NULL,
    "CreatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "FK_MemoryVersions_Memories"
        FOREIGN KEY ("MemoryId") REFERENCES "Memories"("MemoryId")
);

CREATE INDEX IF NOT EXISTS "IX_MemoryVersions_MemoryId"
    ON "MemoryVersions" ("MemoryId");

-- ─────────────────────────────────────────────────────────────────────────────
-- 14. MemoryCategories (Phase 3: Extensible multi-valued categories)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "MemoryCategories" (
    "MemoryCategoryId"  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "MemoryId"          BIGINT NOT NULL,
    "Category"          VARCHAR(64) NOT NULL,
    "CreatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "UX_MemoryCategories_Memory_Category"
        UNIQUE ("MemoryId", "Category"),
    CONSTRAINT "FK_MemoryCategories_Memories"
        FOREIGN KEY ("MemoryId") REFERENCES "Memories"("MemoryId") ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS "IX_MemoryCategories_MemoryId"
    ON "MemoryCategories" ("MemoryId");
CREATE INDEX IF NOT EXISTS "IX_MemoryCategories_Category"
    ON "MemoryCategories" ("Category");

-- ─────────────────────────────────────────────────────────────────────────────
-- 15. Entities (Phase 1: Project-scoped normalized named entities)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "Entities" (
    "EntityId"          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ProjectId"         BIGINT NOT NULL,
    "NormalizedName"    VARCHAR(256) NOT NULL,
    "DisplayName"       VARCHAR(256) NOT NULL,
    "EntityType"        VARCHAR(64) NOT NULL,
    "CreatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "UX_Entities_ProjectId_NormalizedName"
        UNIQUE ("ProjectId", "NormalizedName"),
    CONSTRAINT "FK_Entities_Projects"
        FOREIGN KEY ("ProjectId") REFERENCES "Projects"("ProjectId")
);

CREATE INDEX IF NOT EXISTS "IX_Entities_ProjectId"
    ON "Entities" ("ProjectId");

-- ─────────────────────────────────────────────────────────────────────────────
-- 16. MemoryEntities (Phase 1: Memory <-> Entity many-to-many junction)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "MemoryEntities" (
    "MemoryEntityId"    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "MemoryId"          BIGINT NOT NULL,
    "EntityId"          BIGINT NOT NULL,
    "CreatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "UX_MemoryEntities_MemoryId_EntityId"
        UNIQUE ("MemoryId", "EntityId"),
    CONSTRAINT "FK_MemoryEntities_Memories"
        FOREIGN KEY ("MemoryId") REFERENCES "Memories"("MemoryId"),
    CONSTRAINT "FK_MemoryEntities_Entities"
        FOREIGN KEY ("EntityId") REFERENCES "Entities"("EntityId")
);

CREATE INDEX IF NOT EXISTS "IX_MemoryEntities_MemoryId"
    ON "MemoryEntities" ("MemoryId");
CREATE INDEX IF NOT EXISTS "IX_MemoryEntities_EntityId"
    ON "MemoryEntities" ("EntityId");

-- ─────────────────────────────────────────────────────────────────────────────
-- 17. EntityRelationships (Phase 2: Graph memory entity-to-entity relations)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "EntityRelationships" (
    "RelationshipId"    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ProjectId"         BIGINT NOT NULL,
    "ScopeId"           BIGINT NOT NULL,
    "SourceEntityId"    BIGINT NOT NULL,
    "TargetEntityId"    BIGINT NOT NULL,
    "RelationshipType"  VARCHAR(128) NOT NULL,
    "Confidence"        DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    "CreatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "UX_EntityRelationships_Scope_Source_Target_Type"
        UNIQUE ("ScopeId", "SourceEntityId", "TargetEntityId", "RelationshipType"),
    CONSTRAINT "FK_EntityRelationships_Projects"
        FOREIGN KEY ("ProjectId") REFERENCES "Projects"("ProjectId"),
    CONSTRAINT "FK_EntityRelationships_MemoryScopes"
        FOREIGN KEY ("ScopeId") REFERENCES "MemoryScopes"("ScopeId"),
    CONSTRAINT "FK_EntityRelationships_SourceEntity"
        FOREIGN KEY ("SourceEntityId") REFERENCES "Entities"("EntityId"),
    CONSTRAINT "FK_EntityRelationships_TargetEntity"
        FOREIGN KEY ("TargetEntityId") REFERENCES "Entities"("EntityId")
);

CREATE INDEX IF NOT EXISTS "IX_EntityRelationships_ProjectId"
    ON "EntityRelationships" ("ProjectId");
CREATE INDEX IF NOT EXISTS "IX_EntityRelationships_ScopeId"
    ON "EntityRelationships" ("ScopeId");
CREATE INDEX IF NOT EXISTS "IX_EntityRelationships_SourceEntityId"
    ON "EntityRelationships" ("SourceEntityId");
CREATE INDEX IF NOT EXISTS "IX_EntityRelationships_TargetEntityId"
    ON "EntityRelationships" ("TargetEntityId");

-- ─────────────────────────────────────────────────────────────────────────────
-- 18. RelationshipEvidence (Phase 2: Provenance linking relations to memories)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "RelationshipEvidence" (
    "EvidenceId"        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "RelationshipId"    BIGINT NOT NULL,
    "MemoryId"          BIGINT NOT NULL,
    "CreatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "UX_RelationshipEvidence_Relationship_Memory"
        UNIQUE ("RelationshipId", "MemoryId"),
    CONSTRAINT "FK_RelationshipEvidence_EntityRelationships"
        FOREIGN KEY ("RelationshipId") REFERENCES "EntityRelationships"("RelationshipId") ON DELETE CASCADE,
    CONSTRAINT "FK_RelationshipEvidence_Memories"
        FOREIGN KEY ("MemoryId") REFERENCES "Memories"("MemoryId") ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS "IX_RelationshipEvidence_RelationshipId"
    ON "RelationshipEvidence" ("RelationshipId");
CREATE INDEX IF NOT EXISTS "IX_RelationshipEvidence_MemoryId"
    ON "RelationshipEvidence" ("MemoryId");

-- ─────────────────────────────────────────────────────────────────────────────
-- 19. MemoryIngestionJobs (Phase 4A: Durable background ingestion jobs)
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "MemoryIngestionJobs" (
    "JobId"             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ProjectId"         BIGINT NOT NULL,
    "UserId"            BIGINT NOT NULL,
    "ScopeId"           BIGINT NULL,
    "MemoryId"          BIGINT NULL,
    "JobType"           VARCHAR(50) NOT NULL,
    "Status"            VARCHAR(30) NOT NULL DEFAULT 'Pending',
    "Payload"           TEXT NULL,
    "Attempts"          INT NOT NULL DEFAULT 0,
    "MaxAttempts"       INT NOT NULL DEFAULT 3,
    "AvailableAt"       TIMESTAMPTZ NOT NULL,
    "LockedUntil"       TIMESTAMPTZ NULL,
    "LockOwner"         VARCHAR(128) NULL,
    "LastError"         VARCHAR(2048) NULL,
    "CreatedAt"         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "CompletedAt"       TIMESTAMPTZ NULL,

    CONSTRAINT "FK_MemoryIngestionJobs_Projects"
        FOREIGN KEY ("ProjectId") REFERENCES "Projects"("ProjectId"),
    CONSTRAINT "FK_MemoryIngestionJobs_Users"
        FOREIGN KEY ("UserId") REFERENCES "Users"("UserId"),
    CONSTRAINT "FK_MemoryIngestionJobs_Memories"
        FOREIGN KEY ("MemoryId") REFERENCES "Memories"("MemoryId") ON DELETE SET NULL,
    CONSTRAINT "FK_MemoryIngestionJobs_MemoryScopes"
        FOREIGN KEY ("ScopeId") REFERENCES "MemoryScopes"("ScopeId") ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS "IX_MemoryIngestionJobs_Claiming"
    ON "MemoryIngestionJobs" ("Status", "AvailableAt", "LockedUntil");
CREATE INDEX IF NOT EXISTS "IX_MemoryIngestionJobs_User_Project"
    ON "MemoryIngestionJobs" ("UserId", "ProjectId");
CREATE INDEX IF NOT EXISTS "IX_MemoryIngestionJobs_MemoryId"
    ON "MemoryIngestionJobs" ("MemoryId");

-- ─────────────────────────────────────────────────────────────────────────────
-- 20. Application Role Permissions (Conditional / Idempotent)
-- ─────────────────────────────────────────────────────────────────────────────
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'kairo_dev') THEN
        GRANT USAGE ON SCHEMA public TO kairo_dev;
        GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public TO kairo_dev;
        GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public TO kairo_dev;
        ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL PRIVILEGES ON TABLES TO kairo_dev;
        ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL PRIVILEGES ON SEQUENCES TO kairo_dev;
    END IF;
END $$;

